#!/usr/bin/env python3
"""Convert the vendored, integer-grid SVGs to a reproducible 9x9 mcufont atlas.

Standard library only. Sample pixel centres, preserving SVG nonzero fill rules.
Reject unsupported geometry rather than silently rendering a broken glyph.
Dark details and per-icon knockout colours become holes in the monochrome art.
"""
import argparse
import json
import re
import struct
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent


def paths(data):
    tokens = re.findall(r"[A-Za-z]|[-+]?\d*\.?\d+", data)
    polygons, poly, x, y, start = [], [], 0, 0, (0, 0)
    i, command = 0, None
    while i < len(tokens):
        if tokens[i].isalpha():
            command = tokens[i]
            assert command in 'MmLlHhVvZz', f'Unsupported SVG command {command}'
            i += 1
            if command in 'Zz':
                if poly:
                    polygons.append(poly)
                poly, (x, y) = [], start
                continue
        assert command and command not in 'Zz'
        if command in 'MmLl':
            nx, ny = float(tokens[i]), float(tokens[i + 1])
            i += 2
            if command.islower():
                nx, ny = nx + x, ny + y
            x, y = nx, ny
            if command in 'Mm':
                if poly:
                    polygons.append(poly)
                poly, start = [], (x, y)
                command = 'l' if command == 'm' else 'L'
        else:
            value = float(tokens[i]); i += 1
            if command in 'Hh':
                x = value + (x if command == 'h' else 0)
            else:
                y = value + (y if command == 'v' else 0)
        poly.append((x, y))
    if poly:
        polygons.append(poly)
    return polygons


def winding(poly, x, y):
    n = 0
    for (ax, ay), (bx, by) in zip(poly, poly[1:] + poly[:1]):
        side = (bx - ax) * (y - ay) - (x - ax) * (by - ay)
        if ay <= y < by and side > 0:
            n += 1
        elif by <= y < ay and side < 0:
            n -= 1
    return n


def raster(entry):
    if 'rows' in entry:
        rows = entry['rows']
        assert len(rows) == 9 and all(len(row) == 9 and set(row) <= {'.', '#'} for row in rows)
        return [[c == '#' for c in row] for row in rows]
    root = ET.parse(HERE / 'svg' / entry['file']).getroot()
    assert root.attrib['viewBox'] == '0 0 9 9'
    pixels = [[False] * 9 for _ in range(9)]
    for el in root:
        kind, a = el.tag.split('}')[-1], el.attrib
        if kind == 'rect':
            x, y = float(a.get('x', 0)), float(a.get('y', 0))
            w, h = float(a['width']), float(a['height'])
            polys = [[(x, y), (x + w, y), (x + w, y + h), (x, y + h)]]
        elif kind == 'polygon':
            coords = list(map(float, re.findall(r'[-+]?\d*\.?\d+', a['points'])))
            polys = [list(zip(coords[::2], coords[1::2]))]
        elif kind == 'path':
            polys = paths(a['d'])
        else:
            raise ValueError(f'Unsupported SVG element {kind}')
        assert not any(k in a for k in ('transform', 'stroke', 'opacity', 'fill-rule'))
        colour = a['fill'].upper()
        assert re.fullmatch(r'#[0-9A-F]{6}', colour)
        lit = (entry.get('keep_dark', False) or max(int(colour[i:i+2], 16) for i in (1, 3, 5)) > 70) and colour not in entry.get('knockout', [])
        for y in range(9):
            for x in range(9):
                if sum(winding(p, x + .5, y + .5) for p in polys):
                    pixels[y][x] = lit
    return pixels


def outputs():
    entries = json.loads((HERE / 'mapping.json').read_text())
    bitmaps = [raster(e) for e in entries]
    data, mapping, catalog = [], {}, []
    for i, (entry, pixels) in enumerate(zip(entries, bitmaps)):
        assert any(map(any, pixels)), f'Empty glyph: {entry["name"]}'
        for x in range(9):
            column = sum(int(pixels[y][x]) << y for y in range(9))
            data.extend((column & 255, column >> 8))
        for cp in entry['codepoints']:
            key = int(cp, 16) & 0xffff  # mcufont's existing 16-bit Unicode callback
            assert key not in mapping, f'Unicode collision: {cp}'
            mapping[key] = 0xE100 + i
        catalog.append(int(entry['codepoints'][0], 16))
    font = '''// Generated by pixel-icons/generate.py. Artwork: shuqikhor, MIT; see ../pixel-icons/LICENSE.
#define MF_BWFONT_INTERNALS
#include "mf_bwfont.h"
#ifndef MF_BWFONT_VERSION_4_SUPPORTED
#error Incompatible mcufont format
#endif
static const uint8_t pixels[] PROGMEM = {
'''
    for i in range(0, len(data), 18):
        font += '  ' + ', '.join(f'0x{v:02x}' for v in data[i:i+18]) + ',\n'
    font += f'''}};
static const struct mf_bwfont_char_range_s ranges[] = {{
  {{0xE100, {len(entries)}, 0, 0, 2, 9, 9, 0, 0, pixels}}
}};
const struct mf_bwfont_s mf_bwfont_PixelEmoji = {{
  {{"Pixel Icons", "PixelEmoji", 9, 9, 9, 9, 0, 9, 9, 3, 0xE100,
    &mf_bwfont_character_width, &mf_bwfont_render_character}},
  4, 1, ranges
}};
'''
    inc = '// Generated by pixel-icons/generate.py; see LICENSE for artwork attribution.\n'
    inc += 'static const struct { uint16_t key, glyph; } pixelEmojiMap[] = {\n'
    inc += ''.join(f'  {{0x{k:04X}, 0x{v:04X}}},\n' for k, v in sorted(mapping.items()))
    inc += '};\nstatic const uint32_t pixelEmojiCatalog[] = {\n  '
    inc += ', '.join(f'0x{v:X}' for v in catalog) + '\n};\n'
    return {HERE.parent / 'fonts' / 'PixelEmoji.c': font, HERE / 'Map.inc': inc}, bitmaps


def preview(bitmaps, path):
    # Enlarged contact sheet in mapping.json order; white pixels on dark OLED.
    cols, scale, cell = 9, 6, 13
    w, h = cols * cell * scale, ((len(bitmaps) + cols - 1) // cols) * cell * scale
    rows = [bytearray([24] * w) for _ in range(h)]
    for i, bitmap in enumerate(bitmaps):
        for y in range(9):
            for x in range(9):
                for dy in range(scale):
                    py = ((i // cols) * cell + 2 + y) * scale + dy
                    px = ((i % cols) * cell + 2 + x) * scale
                    rows[py][px:px + scale] = bytes([255 if bitmap[y][x] else 24]) * scale
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    png = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 0, 0, 0, 0))
    png += chunk(b'IDAT', zlib.compress(b''.join(b'\x00' + r for r in rows))) + chunk(b'IEND', b'')
    Path(path).write_bytes(png)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--preview')
    args = parser.parse_args()
    files, bitmaps = outputs()
    for path, text in files.items():
        if args.check:
            assert path.read_text() == text, f'Regenerate {path}'
        else:
            path.write_text(text)
    if args.preview:
        preview(bitmaps, args.preview)
    print(f'{len(bitmaps)} glyphs: {"verified" if args.check else "generated"}')
